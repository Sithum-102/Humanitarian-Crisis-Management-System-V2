using Microsoft.EntityFrameworkCore;

namespace HumanitarianCrisis.API.Data;

/// <summary>
/// Adds the audit table to databases created by earlier prototype versions.
/// The SQL is idempotent so existing operational data is preserved.
/// </summary>
public static class AuditLogSchema
{
    public static void EnsureCreated(CrisisDbContext db)
    {
        var sql = db.Database.ProviderName switch
        {
            "Microsoft.EntityFrameworkCore.SqlServer" => SqlServer,
            "Microsoft.EntityFrameworkCore.Sqlite" => Sqlite,
            "Npgsql.EntityFrameworkCore.PostgreSQL" => PostgreSql,
            var provider => throw new InvalidOperationException($"Unsupported database provider for audit log schema: {provider}"),
        };

        db.Database.ExecuteSqlRaw(sql);
    }

    private const string SqlServer = """
        IF OBJECT_ID(N'dbo.AuditLogs', N'U') IS NULL
        BEGIN
            CREATE TABLE [dbo].[AuditLogs] (
                [Id] int IDENTITY(1,1) NOT NULL CONSTRAINT [PK_AuditLogs] PRIMARY KEY,
                [EntityType] nvarchar(100) NOT NULL,
                [EntityId] int NOT NULL,
                [Action] nvarchar(80) NOT NULL,
                [ActorUserId] int NULL,
                [ActorName] nvarchar(254) NOT NULL,
                [ActorRole] nvarchar(80) NOT NULL,
                [FromValue] nvarchar(1000) NULL,
                [ToValue] nvarchar(1000) NULL,
                [Details] nvarchar(2000) NULL,
                [Recommendation] nvarchar(2000) NULL,
                [Confidence] float NULL,
                [OccurredAt] datetime2 NOT NULL
            );
        END
        """;

    private const string Sqlite = """
        CREATE TABLE IF NOT EXISTS "AuditLogs" (
            "Id" INTEGER NOT NULL CONSTRAINT "PK_AuditLogs" PRIMARY KEY AUTOINCREMENT,
            "EntityType" TEXT NOT NULL,
            "EntityId" INTEGER NOT NULL,
            "Action" TEXT NOT NULL,
            "ActorUserId" INTEGER NULL,
            "ActorName" TEXT NOT NULL,
            "ActorRole" TEXT NOT NULL,
            "FromValue" TEXT NULL,
            "ToValue" TEXT NULL,
            "Details" TEXT NULL,
            "Recommendation" TEXT NULL,
            "Confidence" REAL NULL,
            "OccurredAt" TEXT NOT NULL
        );
        """;

    private const string PostgreSql = """
        CREATE TABLE IF NOT EXISTS "AuditLogs" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "EntityType" character varying(100) NOT NULL,
            "EntityId" integer NOT NULL,
            "Action" character varying(80) NOT NULL,
            "ActorUserId" integer NULL,
            "ActorName" character varying(254) NOT NULL,
            "ActorRole" character varying(80) NOT NULL,
            "FromValue" character varying(1000) NULL,
            "ToValue" character varying(1000) NULL,
            "Details" character varying(2000) NULL,
            "Recommendation" character varying(2000) NULL,
            "Confidence" double precision NULL,
            "OccurredAt" timestamp with time zone NOT NULL
        );
        """;
}
