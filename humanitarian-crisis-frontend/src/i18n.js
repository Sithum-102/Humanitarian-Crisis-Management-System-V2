const reversePhrases = new Map();
for (const [english, translations] of Object.entries(phrases)) {
    reversePhrases.set(translations[0], english);
    reversePhrases.set(translations[1], english);
}

export function translateText(value, language) {
    if (!value || language === 'en') return value;
    const leading = value.match(/^\s*/)?.[0] ?? '';
    const trailing = value.match(/\s*$/)?.[0] ?? '';
    const core = value.trim();
    const english = reversePhrases.get(core) || core;
    const translation = phrases[english]?.[language === 'si' ? 0 : 1];
    return translation ? `${leading}${translation}${trailing}` : value;
}

export function applyPageLanguage(language) {
    document.documentElement.lang = language === 'si' ? 'si-LK' : language === 'ta' ? 'ta-LK' : 'en';
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
        const parent = node.parentElement;
        if (!parent || parent.closest('script,style,textarea,select option,.language-picker,[data-no-translate]')) continue;
        const translated = translateText(node.nodeValue, language);
        if (translated !== node.nodeValue) node.nodeValue = translated;
    }
    document.querySelectorAll('input[placeholder],textarea[placeholder],[aria-label],[title]').forEach(element => {
        for (const attribute of ['placeholder', 'aria-label', 'title']) {
            if (element.hasAttribute(attribute)) {
                const value = element.getAttribute(attribute);
                const translated = translateText(value, language);
                if (translated !== value) element.setAttribute(attribute, translated);
            }
        }
    });
}
